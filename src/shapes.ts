/** One character's rings at a cap height, or null for a space or a character the alphabet lacks. */
export function glyphRings(ch: string, size: number): Ring[] | null {
  const g = GLYPHS[ch];
  if (!g) return null;
  const k = size / 6;
  // ":" and "%" are separate pieces, all outsides; any other second ring is a hole
  return orient(g, ch === ":" || ch === "%" ? g.length : 1).map((r) => r.map(([a, b]) => [a * k, b * k] as [number, number]));
}

/** How far along the line a character takes, as a share of the cap height, gap included. */
export const ADVANCE = 5 / 6;
export const hasGlyph = (ch: string) => ch === " " || ch in GLYPHS;
