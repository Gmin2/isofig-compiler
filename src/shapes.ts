// Outlines for the solids that are not boxes: a handful of plain shapes, and a block
// alphabet. Each is a list of rings, the outside first and any holes after it, drawn
// on its own small grid and scaled to the room the solid is given.

type Ring = [number, number][];

export const SHAPES = ["hex", "tri", "diamond", "star", "plus", "arrow", "chevron", "ring", "pill"] as const;
export type ShapeKind = (typeof SHAPES)[number];

// a ring's winding: positive is counter clockwise
const area = (r: Ring) => r.reduce((s, [a, b], i) => { const [c, d] = r[(i + 1) % r.length]!; return s + a * d - c * b; }, 0) / 2;
// the first `outsides` rings counter clockwise, holes clockwise, whatever order they were drawn in
const orient = (rings: Ring[], outsides: number): Ring[] =>
  rings.map((r, i) => (Math.sign(area(r)) === (i < outsides ? 1 : -1) ? r : [...r].reverse()));

const circle = (cx: number, cy: number, r: number, n = 32): Ring =>
  Array.from({ length: n }, (_, i) => [cx + r * Math.cos((2 * Math.PI * i) / n), cy + r * Math.sin((2 * Math.PI * i) / n)]);

// every shape on a unit square, pointing along +u where it points at all
const UNIT: Record<ShapeKind, () => Ring[]> = {
  hex: () => [[[0.25, 0], [0.75, 0], [1, 0.5], [0.75, 1], [0.25, 1], [0, 0.5]]],
  tri: () => [[[0, 0], [1, 0.5], [0, 1]]],
  diamond: () => [[[0.5, 0], [1, 0.5], [0.5, 1], [0, 0.5]]],
  star: () => [Array.from({ length: 10 }, (_, i): [number, number] => {
    const a = Math.PI / 2 + (Math.PI * i) / 5, r = i % 2 ? 0.2 : 0.5;
    return [0.5 + r * Math.cos(a), 0.5 + r * Math.sin(a)];
  })],
  plus: () => [[[0.33, 0], [0.67, 0], [0.67, 0.33], [1, 0.33], [1, 0.67], [0.67, 0.67], [0.67, 1], [0.33, 1], [0.33, 0.67], [0, 0.67], [0, 0.33], [0.33, 0.33]]],
  arrow: () => [[[0, 0.3], [0.58, 0.3], [0.58, 0], [1, 0.5], [0.58, 1], [0.58, 0.7], [0, 0.7]]],
  chevron: () => [[[0, 0], [0.42, 0], [1, 0.5], [0.42, 1], [0, 1], [0.58, 0.5]]],
  ring: () => [circle(0.5, 0.5, 0.5), circle(0.5, 0.5, 0.27).reverse()],
  pill: () => {
    const out: Ring = [];
    for (let i = 0; i <= 12; i++) { const a = -Math.PI / 2 + (Math.PI * i) / 12; out.push([0.75 + 0.25 * Math.cos(a), 0.5 + 0.5 * Math.sin(a)]); }
    for (let i = 0; i <= 12; i++) { const a = Math.PI / 2 + (Math.PI * i) / 12; out.push([0.25 + 0.25 * Math.cos(a), 0.5 + 0.5 * Math.sin(a)]); }
    return [out];
  },
};

/** A shape's rings across a w by v room. point turns the ones that point: +u is the default. */
export function shapeRings(kind: ShapeKind, w: number, v: number, pointed?: "+u" | "-u" | "+v" | "-v"): Ring[] {
  // a triangle points up unless told, like a warning sign or a peak; anything else that points goes along +u
  const point = pointed ?? (kind === "tri" ? "+v" : "+u");
  // the pill lies along its longer side, whichever that is
  let rings = UNIT[kind]();
  if (kind === "pill" && v > w) rings = rings.map((r) => r.map(([a, b]) => [b, a] as [number, number]).reverse());
  const turn = ([a, b]: [number, number]): [number, number] =>
    point === "-u" ? [1 - a, b] : point === "+v" ? [1 - b, a] : point === "-v" ? [b, 1 - a] : [a, b];
  return orient(rings.map((r) => r.map(turn).map(([a, b]) => [a * w, b * v] as [number, number])), 1);
}

