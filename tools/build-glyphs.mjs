// Turns a folder of material symbols svgs into the glyph catalogue the compiler
// reads. Run it again whenever the icon set is updated.
//
//   node tools/build-glyphs.mjs <svg-dir> [out]
//
// The set ships one <path> per icon on a 960 grid whose y runs from -960 to 0.
// We keep the path exactly as it is and let the compiler shift it down, so this
// step stays a copy rather than a redraw: nothing here can distort a glyph.
//
// Everything lands in one file as a single string, parsed on first lookup. An
// object literal of four thousand entries costs real milliseconds to parse at
// every start, and a string costs almost nothing until something asks for a
// glyph.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { basename, join } from "node:path";

const args = process.argv.slice(2).filter((a) => !a.startsWith("--"));
// the set ships an outline and a filled twin of every icon. the outline is the
// default: the filled twins clog into blobs once they are small and laid flat on
// a face, and their black masses fight the line drawing round them
const filled = process.argv.includes("--filled");
const [dir, out = "src/glyphs.generated.ts"] = args;
if (!dir) {
  console.error("usage: node tools/build-glyphs.mjs <svg-dir> [out]");
  process.exit(2);
}

const rows = [];
let skipped = 0;
for (const file of readdirSync(dir).sort()) {
  if (!file.endsWith(".svg")) continue;
  let name = basename(file, ".svg");
  if (filled) {
    if (!name.endsWith("-fill")) continue;
    name = name.slice(0, -"-fill".length);
  } else if (name.endsWith("-fill")) continue;
  const svg = readFileSync(join(dir, file), "utf8");
  const paths = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((m) => m[1]);
  if (!paths.length) {
    skipped++;
    continue;
  }
  // a name with a tab or newline in it would break the format; none have one,
  // and this makes sure of it
  if (/[\t\n]/.test(name) || paths.some((p) => /[\t\n]/.test(p))) {
    skipped++;
    continue;
  }
  rows.push(`${name}\t${paths.join(" ")}`);
}

const body = rows.join("\n").replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");

writeFileSync(out, `// Generated by tools/build-glyphs.mjs. Do not edit.
//
// Material Symbols, Apache 2.0. The licence and where they came from are in
// icons/.
//
// One icon per line: name, a tab, then its path data on the set's own 960 grid
// with y running from -960 to 0.
export const GRID = 960;

export const CATALOGUE = \`${body}\`;
`);

console.log(`${rows.length} glyphs -> ${out}${skipped ? `, ${skipped} skipped` : ""}`);
